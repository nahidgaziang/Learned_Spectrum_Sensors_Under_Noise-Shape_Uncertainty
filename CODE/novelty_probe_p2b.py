"""Probe P2b (2026-10-05, PRELIMINARY): calibrates the LMPI-equivalence evidence of novelty_probes.p2.
(a) Reference agreement. On identical test windows (same evaluation seed => same windows for every detector), how
    close are the white-trained networks to EACH OTHER, and how close are the LMPI and the band ratio? If the
    network-LMPI agreement is no higher than the network-network or network-BAND agreement, "the networks are the
    LMPI test" is not supported beyond "they are second-order detectors".
(b) Implicit spectral template. Regress each detector's score (logits for networks, raw statistic for BAND/LMPI) on
    the normalised periodogram X_k = P_k / sum_j P_j (128 bins) over pooled windows (H0 white, H1 white -10 dB,
    Gaussian surrogate -10 dB). Rows of X sum to 1, so only the centred weight vector is identifiable (ridge picks
    it). Compare the centred fitted weights with the centred signal PSD p (the LMPI template) and with the template
    recovered from BAND. The LMPI score is exactly linear in X (R^2 = 1, cosine 1: sanity check of the method).
(c) Effective design SNR (added the same day): best fit of each fitted template within the family of most powerful
    invariant Gaussian tests, bin weights g p/(1 + g p), g on a -40..+20 dB grid (training SNRs: U(-20, 20) dB).
The windows are regenerated by calling evaluate.evaluate with the same defaults as the saved network scores and a
recording score function (generation order: calibration, then raw keys in insertion order).
Writes RESULTS/novelty_probe_p2b.json.   usage: py -3.12 novelty_probe_p2b.py"""
import itertools, json, os, sys
import numpy as np
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import evaluate as E
import wall as W

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "RESULTS", "novelty_probe_p2b.json")
N, SPS = 128, 8
NETS = ["CLDNN", "CovCNN", "GapCNN", "ResNet1D", "STFTCNN"]
KEY = "h1_white_-10"
POOL = ["h0_white", "h1_white_-10", "sur_white_-10"]
N_CAL, N_CAL_SHAPE = 20000, 4000            # evaluate() defaults (must match the saved runs)


def run_seed(s):
    p = W.signal_psd(N, sps=SPS)
    w = p / p.sum()
    rec = []

    def lmpi(x):
        P = np.abs(np.fft.fft(x, axis=1)) ** 2
        X = P / P.sum(1, keepdims=True)
        rec.append(X.astype(np.float32))
        return X @ w

    res, raw = E.evaluate(lmpi, N, SPS, s)
    allX = np.concatenate(rec)
    off = N_CAL + N_CAL_SHAPE * len(E.all_shapes())
    assert len(allX) == off + sum(len(v) for v in raw.values()), "window bookkeeping mismatch"
    Xk = {}
    for k, v in raw.items():
        if k in POOL:
            Xk[k] = allX[off:off + len(v)]
            assert np.allclose(Xk[k] @ w, v, rtol=1e-4, atol=1e-6), f"LMPI replay mismatch for {k}"
        off += len(v)
    del allX, rec

    det = {"LMPI": ({k: raw[k] for k in POOL}, res["thresholds"]["nominal"])}
    zb = np.load(os.path.join(ROOT, "RESULTS", "scores", f"cls_BAND_N128_sps8_s{s}.npz"))
    tb = json.load(open(os.path.join(ROOT, "RESULTS", "runs", f"cls_BAND_N128_sps8_s{s}.json")))["eval"]["thresholds"]["nominal"]
    det["BAND"] = ({k: zb[k] for k in POOL}, tb)
    for net in NETS:
        fz = os.path.join(ROOT, "RESULTS", "scores", f"{net}_WHITE_N128_sps8_s{s}.npz")
        z = np.load(fz)
        tn = json.load(open(fz.replace("scores", "runs").replace(".npz", ".json")))["eval"]["thresholds"]["nominal"]
        det[net] = ({k: z[k] for k in POOL}, tn)

    # (a) pairwise agreement on the H1 key (identical windows)
    pairs = {}
    for a, b in itertools.combinations(det, 2):
        sa, ta = det[a][0][KEY], det[a][1]
        sb, tb_ = det[b][0][KEY], det[b][1]
        pairs[f"{a}|{b}"] = {"rho": float(stats.spearmanr(sa, sb)[0]),
                             "agree": float(np.mean((sa > ta) == (sb > tb_)))}

    # (b) implicit spectral templates
    X = np.concatenate([Xk[k] for k in POOL]).astype(np.float64)
    Xc = X - X.mean(0)
    G = Xc.T @ Xc
    lam = 1e-6 * np.trace(G) / G.shape[0]
    pc = w - w.mean()
    tmpl, fit = {}, {}
    for name, (sc, _) in det.items():
        y = np.concatenate([np.asarray(sc[k], float) for k in POOL])
        yc = y - y.mean()
        beta = np.linalg.solve(G + lam * np.eye(G.shape[0]), Xc.T @ yc)
        r2 = 1 - np.sum((yc - Xc @ beta) ** 2) / np.sum(yc ** 2)
        tmpl[name] = beta - beta.mean()
        fit[name] = {"r2_linear": float(r2)}
    cos = lambda u, v: float(u @ v / (np.linalg.norm(u) * np.linalg.norm(v)))
    for name in det:
        fit[name]["cos_with_p"] = cos(tmpl[name], pc)
        fit[name]["cos_with_band_template"] = cos(tmpl[name], tmpl["BAND"])
    fit["_reference_cos_p_vs_band_template"] = cos(pc, tmpl["BAND"])
    # (c) effective design SNR: the most powerful invariant test of a Gaussian signal with PSD g*p (unit-mean p) in
    #     white noise of unknown level is x^H[I - (I + g T(p))^-1]x / x^H x, i.e. bin weights g p/(1 + g p)
    #     (circulant approximation); g -> 0 gives the LMPI template (∝ p), g -> inf the support indicator.
    pu = p / p.mean()
    grid = np.arange(-40.0, 20.01, 0.5)
    for name in det:
        cs = []
        for gdb in grid:
            g = 10 ** (gdb / 10)
            t = g * pu / (1 + g * pu)
            cs.append(cos(tmpl[name], t - t.mean()))
        i = int(np.argmax(cs))
        fit[name]["best_design_snr_db"] = float(grid[i])
        fit[name]["cos_at_best_design_snr"] = float(cs[i])
        fit[name]["cos_at_lmpi_limit"] = float(cs[0])
    return {"pairs_h1_white_-10": pairs, "templates": fit,
            "template_p_centred": pc.tolist(), "template_band_centred": tmpl["BAND"].tolist(),
            "template_nets_centred": {n: tmpl[n].tolist() for n in NETS}}


def summarise(out):
    seeds = [k for k in out if k.startswith("s")]
    top = ["CLDNN", "CovCNN", "GapCNN"]

    def collect(f):
        return [v for s in seeds for k, v in out[s]["pairs_h1_white_-10"].items() if f(*k.split("|"))]
    groups = {
        "net_net (CLDNN/CovCNN/GapCNN)": collect(lambda a, b: a in top and b in top),
        "net_LMPI (CLDNN/CovCNN/GapCNN)": collect(lambda a, b: {a, b} & set(top) and "LMPI" in (a, b)),
        "net_BAND (CLDNN/CovCNN/GapCNN)": collect(lambda a, b: {a, b} & set(top) and "BAND" in (a, b)),
        "LMPI_BAND": collect(lambda a, b: {a, b} == {"LMPI", "BAND"}),
        "weak_net_LMPI (ResNet1D/STFTCNN)": collect(lambda a, b: {a, b} & {"ResNet1D", "STFTCNN"} and "LMPI" in (a, b)),
        "weak_net_top_net": collect(lambda a, b: bool({a, b} & {"ResNet1D", "STFTCNN"}) and bool({a, b} & set(top))),
    }
    summ = {}
    for g, v in groups.items():
        r = [x["rho"] for x in v]
        a = [x["agree"] for x in v]
        summ[g] = {"n": len(v), "rho_range": [min(r), max(r)], "agree_range": [min(a), max(a)]}
    t = {}
    for name in ["LMPI", "BAND"] + NETS:
        c = [out[s]["templates"][name]["cos_with_p"] for s in seeds]
        cb = [out[s]["templates"][name]["cos_with_band_template"] for s in seeds]
        r2 = [out[s]["templates"][name]["r2_linear"] for s in seeds]
        bd = [out[s]["templates"][name]["best_design_snr_db"] for s in seeds]
        cbd = [out[s]["templates"][name]["cos_at_best_design_snr"] for s in seeds]
        t[name] = {"cos_with_p_range": [min(c), max(c)], "cos_with_band_range": [min(cb), max(cb)],
                   "p_closer_than_band": f"{sum(x > y for x, y in zip(c, cb))}/{len(seeds)}",
                   "r2_linear_range": [min(r2), max(r2)],
                   "best_design_snr_db": bd, "cos_at_best_design_snr_range": [min(cbd), max(cbd)]}
    t["_reference_cos_p_vs_band_template"] = [out[s]["templates"]["_reference_cos_p_vs_band_template"] for s in seeds]
    return {"agreement": summ, "templates": t}


if __name__ == "__main__":
    out = {"_note": "PRELIMINARY probe (novelty_probe_p2b.py); not paper results."}
    for s in (0, 1, 2):
        out[f"s{s}"] = run_seed(s)
        print(f"seed {s} done", flush=True)
    out["summary"] = summarise(out)
    print(json.dumps(out["summary"], indent=1))
    with open(OUT, "w") as fh:
        json.dump(out, fh, indent=1)
